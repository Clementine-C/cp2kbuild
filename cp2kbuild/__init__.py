def render(result: BuildResult, title: str | None = None) -> str:
    """Convenience wrapper producing the final input text of a build result."""
    heading = title or f"CP2K input generated by cp2kbuild {__version__}"
    return render_document(result.sections, title=heading, notes=result.notes)
